#!/usr/bin/env node
/* Novus Admin Kit parity generator. Sources: data/dataset.json and shared/
   (novus-admin.css, novus-admin.js, console-pages.js, icons.mjs). Emits:
   - Blazor seed data, the static flavors' data module, chart data;
   - copies of the shared console layer (CSS + progressive JS) into every flavor,
     and the static flavors' page behaviour (console-pages.js);
   - the console shell (header with user menu, grouped side navigation, sign-in
     brand panel, signed-out card, filter bar, list footers) as static markup
     between SHELL markers and as generated Razor components for both Blazor
     projects;
   - table rows between DATA markers, so JS-off pages are complete.
   Parity check (constitution Quality Gate 10): node generate.mjs --check writes
   nothing and exits 1 listing every emitted file that differs from its source. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { icons, svg } from "../shared/icons.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const KITS = join(HERE, "..");
const CHECK = process.argv.includes("--check");
const d = JSON.parse(readFileSync(join(HERE, "dataset.json"), "utf8"));

const drift = [];
function emit(path, content) {
  if (!existsSync(dirname(path))) return;
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) return;
  if (CHECK) { drift.push(relative(KITS, path)); return; }
  writeFileSync(path, content);
  console.log("wrote", relative(KITS, path));
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const money = (n) => n.toFixed(2);
const time = (ts) => ts.slice(11, 16);
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const statusTone = { settled: "success", pending: "warning", failed: "danger" };
const healthTone = { healthy: "success", degraded: "warning", offline: "danger" };

