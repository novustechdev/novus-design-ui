/* ---- Static pages: SHELL and DATA blocks ---- */
const chip = (kind, value, tone) =>
  `<span class="badge badge--${tone}"><span class="badge__dot"></span> ${kind} · ${esc(cap(value))}</span>`;

const txRow = (t) => `<tr data-id="${t.id}" data-status="${t.status}" data-product="${t.product}" data-terminal="${t.terminal}" data-amount="${money(t.amount)}">
  <td><code>${t.id}</code></td><td>${time(t.ts)}</td><td>${t.terminal}</td>
  <td>${t.product}</td><td class="num">${money(t.amount)}</td>
  <td>${chip("Status", t.status, statusTone[t.status])}</td>
  <td class="cell--actions"><button class="btn btn--ghost btn--sm" data-detail="${t.id}">Detail</button></td>
</tr>`;

const termRow = (t) => `<tr>
  <td><code>${t.id}</code></td><td>${esc(t.location)}</td><td>${t.product}</td>
  <td class="num">${t.uptime.toFixed(1)}%</td>
  <td>${chip("Health", t.health, healthTone[t.health])}</td><td>${time(t.lastSeen)}</td>
</tr>`;

const blocks = {
  kpis: d.kpis.map((k) => `<div class="stat"><span class="stat__value">${esc(k.value)}</span><span class="stat__label">${esc(k.label)}</span></div>`).join("\n"),
  signals: d.signals.map((s) => `<div class="card signal signal--${s.tone}">
  <p class="eyebrow">${esc(s.eyebrow)}</p>
  <h3>${esc(s.headline)}</h3>
  <p class="muted">${esc(s.detail)}</p>
</div>`).join("\n"),
  "recent-transactions": d.transactions.slice(0, 6).map(txRow).join("\n"),
  transactions: d.transactions.map(txRow).join("\n"),
  terminals: [...d.terminals].sort((a, b) => (a.health === "healthy") - (b.health === "healthy")).map(termRow).join("\n"),
};

const PAGES = ["index.html", "analytics.html", "transactions.html", "datagrid.html", "terminals.html", "settings.html", "login.html", "signed-out.html"];
for (const flavor of ["tailwind", "material"]) {
  for (const page of PAGES) {
    const p = join(KITS, flavor, page);
    if (!existsSync(p)) continue;
    let html = readFileSync(p, "utf8");
    const shells = {
      header: headerTpl("signed-out.html"),
      nav: navHtml(page),
      "auth-brand": brandTpl,
      "signed-out": signedOutTpl("login.html"),
      "tx-filterbar": filterbarTpl(flavor),
      "grid-search": gridSearchTpl(flavor),
      "listfooter-tx": listfooterTpl("tx"),
      "listfooter-grid": listfooterTpl("grid"),
      pwtoggle: pwtoggleTpl(flavor),
    };
    for (const [name, markup] of Object.entries(shells)) {
      html = html.replace(new RegExp(`(<!--SHELL:${name}-->)[\\s\\S]*?(<!--/SHELL:${name}-->)`, "g"), `$1\n${htmlIcons(markup)}\n$2`);
    }
    for (const [name, markup] of Object.entries(blocks)) {
      html = html.replace(new RegExp(`(<!--DATA:${name}-->)[\\s\\S]*?(<!--/DATA:${name}-->)`, "g"), `$1\n${markup}\n$2`);
    }
    emit(p, html);
  }
}

if (CHECK) {
  if (drift.length) {
    console.log(`parity drift in ${drift.length} file(s):\n  ${drift.join("\n  ")}\nrun: node admin-kits/data/generate.mjs`);
    process.exit(1);
  }
  console.log("parity: every generated file matches its source");
}
