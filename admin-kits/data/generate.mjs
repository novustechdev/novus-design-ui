#!/usr/bin/env node
/* Novus Admin Kit parity generator. Single source: dataset.json.
   Emits the Blazor seed data, the Tailwind data module, and injects static
   table rows into the Tailwind pages between DATA markers, so both flavors
   render identical content (and JS-off pages are complete).
   Parity check: run this, then `git diff --exit-code admin-kits`. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const d = JSON.parse(readFileSync(join(HERE, "dataset.json"), "utf8"));

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const money = (n) => n.toFixed(2);
const time = (ts) => ts.slice(11, 16);
const statusTone = { settled: "success", pending: "warning", failed: "danger" };
const healthTone = { healthy: "success", degraded: "warning", offline: "danger" };

/* ---- Blazor: Data/SeedData.cs ---- */
const cs = `// GENERATED by admin-kits/data/generate.mjs from dataset.json. Do not edit.
namespace NovusAdminKit.Data;

public record Kpi(string Value, string Label);
public record Signal(string Tone, string Eyebrow, string Headline, string Detail);
public record Transaction(string Id, string Ts, string Terminal, string Product, decimal Amount, string Currency, string Status);
public record Terminal(string Id, string Location, string Product, double Uptime, string Health, string LastSeen);

public static class SeedData
{
    public static readonly Kpi[] Kpis =
    {
${d.kpis.map((k) => `        new("${k.value}", "${k.label}"),`).join("\n")}
    };

    public static readonly Signal[] Signals =
    {
${d.signals.map((s) => `        new("${s.tone}", "${s.eyebrow}", "${s.headline}", "${s.detail}"),`).join("\n")}
    };

    public static readonly Transaction[] Transactions =
    {
${d.transactions.map((t) => `        new("${t.id}", "${t.ts}", "${t.terminal}", "${t.product}", ${money(t.amount)}m, "${t.currency}", "${t.status}"),`).join("\n")}
    };

    public static readonly Terminal[] Terminals =
    {
${d.terminals.map((t) => `        new("${t.id}", "${t.location}", "${t.product}", ${t.uptime}, "${t.health}", "${t.lastSeen}"),`).join("\n")}
    };
}
`;
const csOut = join(HERE, "../blazor/Data/SeedData.cs");
if (existsSync(dirname(csOut))) { writeFileSync(csOut, cs); console.log("wrote", csOut); }

/* ---- Tailwind: src/data.js ---- */
const js = `// GENERATED by admin-kits/data/generate.mjs from dataset.json. Do not edit.
export const kpis = ${JSON.stringify(d.kpis, null, 1)};
export const signals = ${JSON.stringify(d.signals, null, 1)};
export const transactions = ${JSON.stringify(d.transactions, null, 1)};
export const terminals = ${JSON.stringify(d.terminals, null, 1)};
`;
const jsHourly = `export const hourly = ${JSON.stringify(d.hourly, null, 1)};\n`;
for (const flavor of ["tailwind", "material"]) {
  const jsOut = join(HERE, `../${flavor}/src/data.js`);
  if (existsSync(dirname(jsOut))) { writeFileSync(jsOut, js + jsHourly); console.log("wrote", jsOut); }
}

/* ---- Blazor + WASM demo: chart-data.json for the analytics interop ---- */
for (const rel of ["../blazor/wwwroot", "../blazor-demo/wwwroot"]) {
  const dir = join(HERE, rel);
  if (existsSync(dir)) {
    writeFileSync(join(dir, "chart-data.json"), JSON.stringify(d.hourly));
    console.log("wrote", join(dir, "chart-data.json"));
  }
}

/* ---- Tailwind pages: inject static markup between DATA markers ---- */
const chip = (kind, value, tone) =>
  `<span class="badge badge--${tone}"><span class="badge__dot"></span> ${kind} · ${esc(value[0].toUpperCase() + value.slice(1))}</span>`;

const txRow = (t) => `<tr data-status="${t.status}" data-id="${t.id}">
  <td><code>${t.id}</code></td><td>${time(t.ts)}</td><td>${t.terminal}</td>
  <td>${t.product}</td><td class="num">${money(t.amount)}</td>
  <td>${chip("Status", t.status, statusTone[t.status])}</td>
  <td><button class="btn btn--ghost btn--sm" data-detail="${t.id}">Detail</button></td>
</tr>`;

const termRow = (t) => `<tr>
  <td><code>${t.id}</code></td><td>${esc(t.location)}</td><td>${t.product}</td>
  <td class="num">${t.uptime.toFixed(1)}%</td>
  <td>${chip("Health", t.health, healthTone[t.health])}</td><td>${time(t.lastSeen)}</td>
</tr>`;

const blocks = {
  kpis: d.kpis.map((k) => `<div class="stat"><span class="stat__value">${esc(k.value)}</span><span class="stat__label">${esc(k.label)}</span></div>`).join("\n"),
  signals: d.signals.map((s) => `<div class="card signal signal--${s.tone}">
  <p class="eyebrow">${esc(s.eyebrow)}</p>
  <h3>${esc(s.headline)}</h3>
  <p class="muted">${esc(s.detail)}</p>
</div>`).join("\n"),
  "recent-transactions": d.transactions.slice(0, 6).map(txRow).join("\n"),
  transactions: d.transactions.map(txRow).join("\n"),
  terminals: [...d.terminals].sort((a, b) => (a.health === "healthy") - (b.health === "healthy")).map(termRow).join("\n"),
};

for (const [flavor, page] of ["tailwind", "material"].flatMap((f) =>
  ["index.html", "transactions.html", "terminals.html", "settings.html", "analytics.html", "datagrid.html"].map((pg) => [f, pg]))) {
  const p = join(HERE, `../${flavor}`, page);
  if (!existsSync(p)) continue;
  let html = readFileSync(p, "utf8");
  let touched = false;
  for (const [name, markup] of Object.entries(blocks)) {
    const re = new RegExp(`(<!--DATA:${name}-->)[\\s\\S]*?(<!--/DATA:${name}-->)`, "g");
    if (re.test(html)) { html = html.replace(re, `$1\n${markup}\n$2`); touched = true; }
  }
  if (touched) { writeFileSync(p, html); console.log("injected", page); }
}
